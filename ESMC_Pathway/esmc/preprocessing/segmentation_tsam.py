# 3. DATA VALIDATION (no AMPL) -- requires tsam and real data
# ===========================================================================

def validate_segmentation(ts_td_by_region, n_seg, nbr_td, eud_series=DEFAULT_EUD_SERIES,
                          rmse_tol=None):
    """Validate segmented data before running AMPL. Returns a results dict.

    Checks:
      (1) sum_s t_op[s,td] == 24 for every TD.
      (2) Identity with n_seg = 24: re-segmenting reproduces the original ts_td.
      (3) Reconstruction RMSE per series (informative; enforced if rmse_tol is set).
    """
    results = {'n_seg': n_seg, 'checks': {}}

    # (1) main segmentation
    durs = tsam_segment_durations(ts_td_by_region, n_seg, nbr_td)
    t_op = make_t_op_df(durs, n_seg)
    ok_sum = bool((t_op.sum(axis=0).round().astype(int) == 24).all())
    results['checks']['sum_t_op_eq_24'] = ok_sum
    results['t_op'] = t_op

    # (2) identity with n_seg = 24
    durs24 = tsam_segment_durations(ts_td_by_region, 24, nbr_td)
    ident_ok = all(int(round(sum(d))) == 24 and len(d) == 24 for d in durs24.values())
    max_abs = 0.0
    for region, ts_td in ts_td_by_region.items():
        seg24 = segment_ts_td(ts_td, durs24, eud_series)
        a = ts_td.sort_index()
        b = seg24.sort_index()
        b.index = a.index  # hour == segment
        max_abs = max(max_abs, float(np.nanmax(np.abs(a.to_numpy() - b.to_numpy()))))
    results['checks']['identity_nseg24'] = bool(ident_ok and max_abs < 1e-9)
    results['identity_max_abs_err'] = max_abs

    # (3) reconstruction RMSE for the requested n_seg
    rmse_by_series = {}
    for region, ts_td in ts_td_by_region.items():
        seg = segment_ts_td(ts_td, durs, eud_series)
        for s in dict.fromkeys(ts_td.index.get_level_values(0)):
            how = 'sum' if s in eud_series else 'mean'
            orig = ts_td.loc[(s, slice(None)), :].droplevel(0).sort_index()
            rec = np.zeros_like(orig.to_numpy(), dtype=float)
            for j, td in enumerate(orig.columns):
                for k, (a, b) in enumerate(bounds_from_durations(durs[td]), start=1):
                    val = seg.loc[(s, k), td]
                    # back to hours: EUD spread as val/dur, c_p_t repeated
                    rec[a:b, j] = (val / (b - a)) if how == 'sum' else val
            err = orig.to_numpy() - rec
            rmse_by_series[f"{region}|{s}"] = float(np.sqrt(np.nanmean(err ** 2)))
    results['rmse_by_series'] = rmse_by_series
    if rmse_tol is not None:
        results['checks']['rmse_below_tol'] = all(v <= rmse_tol for v in rmse_by_series.values())

    results['all_passed'] = all(results['checks'].values())
    return results


