# 4. SELF-TEST of the pure core (no tsam)
# ===========================================================================

def _selftest():
    print("== Self-test: pure core (no tsam) ==")
    rng = np.random.default_rng(1)
    nbr_td = 3
    hours = np.arange(1, 25)
    series = ['ELECTRICITY', 'HEAT_LOW_T_SH', 'WIND_ONSHORE', 'PV']  # 2 EUD + 2 res

    # synthetic ts_td for one region: MultiIndex (series, hour) x TD
    idx = pd.MultiIndex.from_product([series, hours], names=['ts', 'H_of_D'])
    ts_td = pd.DataFrame(rng.random((len(idx), nbr_td)) , index=idx,
                         columns=pd.Index([1, 2, 3], name='TD_number'))

    # --- n_seg = 24: 24 segments of 1 h ---
    durs24 = {td: [1] * 24 for td in [1, 2, 3]}
    seg24 = segment_ts_td(ts_td, durs24)
    b = seg24.sort_index(); a = ts_td.sort_index(); b.index = a.index
    err24 = float(np.nanmax(np.abs(a.to_numpy() - b.to_numpy())))
    print(f"  [n_seg=24] ts_td identity: max|err| = {err24:.2e}  -> "
          f"{'OK' if err24 < 1e-12 else 'FAIL'}")

    # --- n_seg = 4: 6 h segments. Check SUM vs MEAN ---
    durs4 = {td: [6, 6, 6, 6] for td in [1, 2, 3]}
    seg4 = segment_ts_td(ts_td, durs4)
    # EUD (ELECTRICITY): segment 1 = sum of hours 1..6
    elec_h = ts_td.loc[('ELECTRICITY', slice(None)), 1].droplevel(0).sort_index().to_numpy()
    exp_sum = elec_h[0:6].sum()
    got_sum = seg4.loc[('ELECTRICITY', 1), 1]
    print(f"  [n_seg=4] EUD seg1 = SUM(h1..6): expected {exp_sum:.6f} got {got_sum:.6f}  -> "
          f"{'OK' if abs(exp_sum - got_sum) < 1e-12 else 'FAIL'}")
    # c_p_t (WIND): segment 1 = mean of hours 1..6
    wind_h = ts_td.loc[('WIND_ONSHORE', slice(None)), 1].droplevel(0).sort_index().to_numpy()
    exp_mean = wind_h[0:6].mean()
    got_mean = seg4.loc[('WIND_ONSHORE', 1), 1]
    print(f"  [n_seg=4] c_p_t seg1 = MEAN(h1..6): expected {exp_mean:.6f} got {got_mean:.6f}  -> "
          f"{'OK' if abs(exp_mean - got_mean) < 1e-12 else 'FAIL'}")
    # EUD energy conservation: sum_s ts_seg = sum_h ts_td (per TD)
    cons = abs(seg4.loc[('ELECTRICITY', slice(None)), 1].sum() -
               ts_td.loc[('ELECTRICITY', slice(None)), 1].sum())
    print(f"  [n_seg=4] EUD conservation (sum_s == sum_h): |diff| = {cons:.2e}  -> "
          f"{'OK' if cons < 1e-12 else 'FAIL'}")

    # --- t_op and t_end ---
    t_op = make_t_op_df(durs4, 4)
    print(f"  t_op sums to 24/TD: {'OK' if (t_op.sum().round().astype(int) == 24).all() else 'FAIL'}")
    t_end = t_end_from_t_op(t_op)
    exp_tend = [6, 12, 18, 24]
    print(f"  t_end TD1 = {t_end[1].tolist()} (expected {exp_tend})  -> "
          f"{'OK' if t_end[1].tolist() == exp_tend else 'FAIL'}")
    t_end24 = t_end_from_t_op(make_t_op_df(durs24, 24))
    print(f"  t_end(n_seg=24) == 1..24: "
          f"{'OK' if t_end24[1].tolist() == list(range(1, 25)) else 'FAIL'}")

    # --- T_H_TD ---
    td_of_days = np.resize([1, 2, 3], 365)
    th24 = build_segmented_t_h_td(td_of_days, 24)
    th4 = build_segmented_t_h_td(td_of_days, 4)
    print(f"  T_H_TD n_seg=24: {len(th24)} rows (expected 8760)  -> "
          f"{'OK' if len(th24) == 8760 else 'FAIL'}")
    print(f"  T_H_TD n_seg=4 : {len(th4)} rows (expected {365*4})  -> "
          f"{'OK' if len(th4) == 365*4 else 'FAIL'}")
    print(f"  T_H_TD n_seg=4 H_of_D in 1..4: "
          f"{'OK' if set(th4['H_of_D'].unique()) == {1,2,3,4} else 'FAIL'}")

    # --- 3D state_of_charge_ev (MAX) ---
    # example pattern: 0.6 at hour 7, zero elsewhere
    ev = {'CAR_BEV': [0.0]*6 + [0.6] + [0.0]*17}
    # n_seg = 24: hour 7 -> 0.6 in every TD, 0 elsewhere
    ev24 = build_state_of_charge_ev_3d(ev, durs24, 24)['CAR_BEV']
    ok_bcast = (abs(ev24.loc[7, 1] - 0.6) < 1e-12 and
                abs(ev24.drop(index=7).to_numpy().max()) < 1e-12 and
                (ev24.loc[7] == 0.6).all())
    print(f"  [EV n_seg=24] hourly pattern copied (0.6 only in seg 7, all TDs): "
          f"{'OK' if ok_bcast else 'FAIL'}")
    # n_seg = 4: hour 7 falls in segment 2 (hours 7..12) -> MAX = 0.6
    ev4 = build_state_of_charge_ev_3d(ev, durs4, 4)['CAR_BEV']
    ok_max = (abs(ev4.loc[2, 1] - 0.6) < 1e-12 and
              abs(ev4.drop(index=2).to_numpy().max()) < 1e-12)
    print(f"  [EV n_seg=4] MAX keeps 0.6 in the segment containing hour 7: "
          f"{'OK' if ok_max else 'FAIL'}  (seg2={ev4.loc[2,1]:.2f})")

    print("== End of self-test ==")


if __name__ == '__main__':
    logging.basicConfig(level=logging.INFO, format='%(levelname)s %(message)s')
    _selftest()
